-- fix-shabnampet-packages-assistanceid.sql
-- اصلاح CompanionAssistanceId اشتباه برای ۲۰ پکیجی که با اسکریپت
-- insert-shabnampet-grooming-packages.sql درج شدند.
--
-- ⚠️ چه اشتباهی رخ داد: در پنل، فیلد «AssistanceId: ۱۱» که روی کارت خدمت «گرومینگ پت»
-- نشون داده می‌شه در واقع یک کد نوع خدمت است، نه شناسه‌ی واقعی رکورد CompanionAssistance.
-- شناسه‌ی واقعی همون رکورد (که در پنل به شکل «#۱۰٬۰۶۴» نمایش داده می‌شه) 10064 است.
-- در نتیجه اسکریپت قبلی، ۲۰ پکیج را به‌اشتباه روی CompanionAssistanceId = 11 درج کرد که
-- متعلق به یک نماینده‌ی کاملاً متفاوت است (همانی که پکیج تستی «ویزیت تلفنی فوری
-- دامپزشک» / #10004 را از قبل داشت) - نه شناسه‌ی واقعی خدمت «گرومینگ پت» شبنم پت.
--
-- زنده روی دیتابیس تأیید شد:
--   - CompanionAssistanceId = 11  → متعلق به نماینده‌ی دیگر (۱ پکیج قدیمی، دست‌نخورده می‌ماند)
--   - CompanionAssistanceId = 10064 → خدمت واقعی «گرومینگ پت» شبنم پت (Companion Id = 10019)، در حال حاضر خالی
--
-- این اسکریپت فقط همان ۲۰ ردیفی که با اسکریپت درج قبلی ساخته شدند را (با Id دقیق،
-- نه با نام، تا هیچ پکیج دیگری دست نخورد) از CompanionAssistanceId=11 به 10064 منتقل می‌کند.

UPDATE dbo.CompanionAssistancePackages
SET CompanionAssistanceId = 10064
WHERE Id IN (10035, 10036, 10037, 10038, 10039, 10040, 10041, 10042, 10043, 10044,
             10045, 10046, 10047, 10048, 10049, 10050, 10051, 10052, 10053, 10054)
  AND CompanionAssistanceId = 11;
